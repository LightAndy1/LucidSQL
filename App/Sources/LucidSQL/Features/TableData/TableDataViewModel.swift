import Foundation
import Observation
import LucidSQLBridge

@Observable
public final class TableDataViewModel: @unchecked Sendable {
    public var currentSchema: String = "public"
    public var currentTable: String = ""
    public var columns: [ColumnMetadata] = []
    public var rows: [RowData] = []
    public private(set) var dataVersion: UInt64 = 0
    public var offset: UInt64 = 0
    public var limit: UInt32 = 100
    public var hasMore: Bool = false
    public var executionDurationMs: UInt64 = 0
    public var isLoading: Bool = false
    public var isApplying: Bool = false
    public var isReadOnly: Bool = false
    public var errorMessage: String? = nil
    public var statusMessage: String? = nil

    public var stagedEdits: [GridCoordinate: CellValue] = [:]
    public var stagedInserts: [StagedInsertRow] = []
    public var stagedDeletes: Set<Int> = []
    public var selectedRowIndex: Int? = nil
    public var pendingActiveCell: GridCoordinate? = nil

    public var showingReviewSheet: Bool = false
    public var showingUnsavedChangesAlert: Bool = false
    public var pendingNavigationAction: (() -> Void)? = nil
    public var hasUncertainCommitOutcome: Bool = false
    public var uncertainCommitOperationsSummary: String? = nil
    public var uncertainCommitDetails: String? = nil
    public var sortColumn: String? = nil
    public var sortDescending: Bool = false
    public var exportViewModel: CsvExportViewModel? = nil

    private var activeLoadTask: Task<Void, Never>? = nil
    private var loadGeneration: UInt64 = 0

    public struct GridCoordinate: Hashable, Sendable {
        public let row: Int
        public let column: Int

        public init(row: Int, column: Int) {
            self.row = row
            self.column = column
        }
    }

    public struct StagedInsertRow: Identifiable, Equatable, Sendable {
        public let id: String
        /// Values keyed by column index (0..<columns.count).
        /// Absent key means `DEFAULT` / omitted from INSERT column list.
        public var cells: [Int: CellValue]

        public init(id: String = UUID().uuidString, cells: [Int: CellValue] = [:]) {
            self.id = id
            self.cells = cells
        }
    }

    public struct StagedEditDiff: Identifiable, Sendable {
        public let id: String
        public let row: Int
        public let column: Int
        public let columnName: String
        public let primaryKeyDescription: String
        public let originalValue: CellValue
        public let newValue: CellValue

        public init(
            id: String = UUID().uuidString,
            row: Int,
            column: Int,
            columnName: String,
            primaryKeyDescription: String,
            originalValue: CellValue,
            newValue: CellValue
        ) {
            self.id = id
            self.row = row
            self.column = column
            self.columnName = columnName
            self.primaryKeyDescription = primaryKeyDescription
            self.originalValue = originalValue
            self.newValue = newValue
        }
    }

    public struct StagedInsertColumnSummary: Identifiable, Sendable {
        public let id: Int
        public let columnName: String
        public let isDefault: Bool
        public let isAutoGenerated: Bool
        public let isMissingRequired: Bool
        public let value: CellValue?
    }

    public struct StagedInsertItem: Identifiable, Sendable {
        public let id: String
        public let gridRow: Int
        public let draftIndex: Int
        public let columns: [StagedInsertColumnSummary]
        public let missingRequiredColumns: [String]
    }

    public struct StagedDeleteItem: Identifiable, Sendable {
        public let id: Int
        public let row: Int
        public let primaryKeyDescription: String
        public let summary: String
    }

    public init() {}

    public var hasPrimaryKey: Bool {
        columns.contains { $0.isPrimaryKey }
    }

    public var isSystemSchema: Bool {
        let lower = currentSchema.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        return lower == "pg_catalog" || lower == "information_schema" || lower.hasPrefix("pg_")
    }

    public var isEditable: Bool {
        hasPrimaryKey && !isReadOnly && !isSystemSchema && !hasUncertainCommitOutcome
    }

    public var nonEditableReason: String? {
        if hasUncertainCommitOutcome {
            return "Last commit outcome was uncertain. Click Reload & Reconcile before applying further edits."
        }
        if isReadOnly {
            return "Read-only guardrail is active. Editing is disabled."
        }
        if isSystemSchema {
            return "System schema '\(currentSchema)' is read-only. Catalog tables cannot be edited."
        }
        if !hasPrimaryKey && !columns.isEmpty {
            return "Table has no primary key. In-grid editing requires a primary key for safe row identity."
        }
        return nil
    }

    public var totalGridRowCount: Int {
        rows.count + stagedInserts.count
    }

    public func isDraftRow(_ row: Int) -> Bool {
        row >= rows.count && row < rows.count + stagedInserts.count
    }

    public func isRowStagedForDeletion(_ row: Int) -> Bool {
        row >= 0 && row < rows.count && stagedDeletes.contains(row)
    }

    public var hasPendingChanges: Bool {
        !stagedEdits.isEmpty || !stagedInserts.isEmpty || !stagedDeletes.isEmpty
    }

    public var totalStagedOperationsCount: Int {
        stagedEdits.count + stagedInserts.count + stagedDeletes.count
    }

    public var stagedRowsCount: Int {
        let persistedRows = Set(stagedEdits.keys.map(\.row)).union(stagedDeletes)
        return persistedRows.count + stagedInserts.count
    }

    public var stagedSummaryText: String {
        var parts: [String] = []
        if !stagedInserts.isEmpty {
            parts.append("\(stagedInserts.count) insert\(stagedInserts.count == 1 ? "" : "s")")
        }
        if !stagedEdits.isEmpty {
            parts.append("\(stagedEdits.count) update\(stagedEdits.count == 1 ? "" : "s")")
        }
        if !stagedDeletes.isEmpty {
            parts.append("\(stagedDeletes.count) delete\(stagedDeletes.count == 1 ? "" : "s")")
        }
        return parts.joined(separator: ", ")
    }

    public func columnHasServerDefault(_ column: ColumnMetadata) -> Bool {
        column.isGenerated || column.isIdentity || column.defaultValue != nil
    }

    public func isColumnAlwaysGenerated(_ column: ColumnMetadata) -> Bool {
        column.isGenerated || column.isIdentityAlways
    }

    public func isColumnTextLike(_ column: ColumnMetadata) -> Bool {
        let lower = column.pgTypeName.lowercased()
        return lower == "text"
            || lower == "varchar"
            || lower == "character varying"
            || lower == "bpchar"
            || lower == "char"
            || lower == "character"
            || lower == "citext"
            || lower == "name"
    }

    public func originalCellValue(row: Int, column: Int) -> CellValue? {
        guard row >= 0, row < rows.count, column >= 0, column < columns.count else {
            return nil
        }
        let rawRow = rows[row]
        let rawColIdx = hasPrimaryKey ? (column + 1) : column
        guard rawColIdx < rawRow.cells.count else { return nil }
        return rawRow.cells[rawColIdx]
    }

    public func rowXmin(row: Int) -> String? {
        guard hasPrimaryKey, row >= 0, row < rows.count else { return nil }
        guard let xmin = rows[row].cells.first?.rawTextValue,
              !xmin.isEmpty,
              xmin.allSatisfy(\.isASCII),
              xmin.allSatisfy(\.isNumber) else {
            return nil
        }
        return xmin
    }

    public func isRowIdentifiable(row: Int) -> Bool {
        guard hasPrimaryKey, rowXmin(row: row) != nil else { return false }
        let pkIndices = columns.indices.filter { columns[$0].isPrimaryKey }
        guard !pkIndices.isEmpty else { return false }
        for pkIdx in pkIndices {
            guard let pkVal = originalCellValue(row: row, column: pkIdx),
                  !pkVal.isNull,
                  !pkVal.isUnsupported else {
                return false
            }
        }
        return true
    }

    public func canDeleteRow(_ row: Int) -> Bool {
        guard isEditable, row >= 0, row < totalGridRowCount else { return false }
        if isDraftRow(row) {
            return true
        }
        return isRowIdentifiable(row: row)
    }

    public func isCellEditable(row: Int, column: Int) -> Bool {
        guard isEditable, row >= 0, row < totalGridRowCount, column >= 0, column < columns.count else {
            return false
        }
        if isColumnAlwaysGenerated(columns[column]) {
            return false
        }
        if isDraftRow(row) {
            return true
        }
        if stagedDeletes.contains(row) {
            return false
        }
        guard isRowIdentifiable(row: row) else {
            return false
        }
        if let orig = originalCellValue(row: row, column: column), orig.isUnsupported {
            return false
        }
        return true
    }

    public func canSetNull(row: Int, column: Int) -> Bool {
        guard isCellEditable(row: row, column: column) else { return false }
        let col = columns[column]
        return col.isNullable && !col.isPrimaryKey
    }

    public func canUseDefault(row: Int, column: Int) -> Bool {
        guard isDraftRow(row), isCellEditable(row: row, column: column) else { return false }
        let draftIdx = row - rows.count
        return stagedInserts[draftIdx].cells[column] != nil
    }

    public func cellState(row: Int, column: Int) -> (value: CellValue, isDefault: Bool, isDirty: Bool) {
        if isDraftRow(row) {
            let draftIdx = row - rows.count
            if let explicit = stagedInserts[draftIdx].cells[column] {
                return (explicit, false, true)
            }
            return (.null, true, false)
        }
        let orig = originalCellValue(row: row, column: column) ?? .null
        let coord = GridCoordinate(row: row, column: column)
        if let edited = stagedEdits[coord] {
            return (edited, false, true)
        }
        return (orig, false, false)
    }

    public func primaryKeyDescription(forRow row: Int) -> String {
        guard row >= 0, row < rows.count else { return "" }
        let rawRow = rows[row]
        let pkCols = columns.filter { $0.isPrimaryKey }
        var pkPairs: [String] = []
        for pkCol in pkCols {
            if let pkIdx = columns.firstIndex(where: { $0.name == pkCol.name }) {
                let cellVal = (pkIdx + 1 < rawRow.cells.count) ? rawRow.cells[pkIdx + 1] : .null
                pkPairs.append("\(pkCol.name): \(cellVal.displayString)")
            }
        }
        return pkPairs.joined(separator: ", ")
    }

    public var stagedDiffs: [StagedEditDiff] {
        guard hasPrimaryKey else { return [] }
        var diffs: [StagedEditDiff] = []

        for (coord, newVal) in stagedEdits.sorted(by: { $0.key.row < $1.key.row || ($0.key.row == $1.key.row && $0.key.column < $1.key.column) }) {
            guard coord.row < rows.count, coord.column < columns.count, !stagedDeletes.contains(coord.row) else {
                continue
            }
            let rawRow = rows[coord.row]
            let col = columns[coord.column]
            let pkDesc = primaryKeyDescription(forRow: coord.row)
            let rawColIdx = coord.column + 1
            let origVal = rawColIdx < rawRow.cells.count ? rawRow.cells[rawColIdx] : .null

            diffs.append(StagedEditDiff(
                row: coord.row,
                column: coord.column,
                columnName: col.name,
                primaryKeyDescription: pkDesc,
                originalValue: origVal,
                newValue: newVal
            ))
        }

        return diffs
    }

    public var stagedDeleteItems: [StagedDeleteItem] {
        guard hasPrimaryKey else { return [] }
        var items: [StagedDeleteItem] = []
        for rowIdx in stagedDeletes.sorted() {
            guard rowIdx >= 0, rowIdx < rows.count else { continue }
            let pkDesc = primaryKeyDescription(forRow: rowIdx)
            var previewCols: [String] = []
            for (colIdx, col) in columns.prefix(3).enumerated() {
                if !col.isPrimaryKey, let val = originalCellValue(row: rowIdx, column: colIdx) {
                    previewCols.append("\(col.name)=\(val.displayString)")
                }
            }
            items.append(StagedDeleteItem(
                id: rowIdx,
                row: rowIdx,
                primaryKeyDescription: pkDesc,
                summary: previewCols.joined(separator: ", ")
            ))
        }
        return items
    }

    public var stagedInsertItems: [StagedInsertItem] {
        var items: [StagedInsertItem] = []
        for (draftIdx, draft) in stagedInserts.enumerated() {
            var colSummaries: [StagedInsertColumnSummary] = []
            var missingRequired: [String] = []
            for (colIdx, col) in columns.enumerated() {
                let explicit = draft.cells[colIdx]
                let isAuto = isColumnAlwaysGenerated(col)
                let isDefault = explicit == nil
                let isMissing = isDefault && !col.isNullable && !columnHasServerDefault(col)
                if isMissing {
                    missingRequired.append(col.name)
                }
                colSummaries.append(StagedInsertColumnSummary(
                    id: colIdx,
                    columnName: col.name,
                    isDefault: isDefault,
                    isAutoGenerated: isAuto,
                    isMissingRequired: isMissing,
                    value: explicit
                ))
            }
            items.append(StagedInsertItem(
                id: draft.id,
                gridRow: rows.count + draftIdx,
                draftIndex: draftIdx,
                columns: colSummaries,
                missingRequiredColumns: missingRequired
            ))
        }
        return items
    }

    public var draftValidationIssues: [String] {
        var issues: [String] = []
        for item in stagedInsertItems {
            if !item.missingRequiredColumns.isEmpty {
                let cols = item.missingRequiredColumns.joined(separator: ", ")
                issues.append("New row +\(item.draftIndex + 1) requires value for NOT NULL column(s): \(cols).")
            }
        }
        return issues
    }

    public func cancelActiveLoad() {
        activeLoadTask?.cancel()
        activeLoadTask = nil
        loadGeneration &+= 1
        isLoading = false
    }

    @discardableResult
    public func beginTableNavigation(schema: String, table: String) -> UInt64 {
        activeLoadTask?.cancel()
        activeLoadTask = nil
        loadGeneration &+= 1

        let switchingTables = self.currentSchema != schema || self.currentTable != table
        self.currentSchema = schema
        self.currentTable = table
        self.offset = 0
        self.sortColumn = nil
        self.sortDescending = false
        self.clearStagedChanges()
        self.statusMessage = nil
        self.errorMessage = nil
        if switchingTables {
            self.columns = []
            self.rows = []
            self.hasMore = false
            self.executionDurationMs = 0
            self.dataVersion &+= 1
        }
        self.isLoading = true
        return self.loadGeneration
    }

    public func startTableLoad(config: ConnectionConfig, schema: String, table: String) {
        let generation = beginTableNavigation(schema: schema, table: table)
        activeLoadTask = Task { @MainActor [weak self] in
            guard let self = self else { return }
            await self.fetchPage(config: config, refreshColumns: true, generation: generation)
        }
    }

    public func loadTable(config: ConnectionConfig, schema: String, table: String) async {
        let generation = beginTableNavigation(schema: schema, table: table)
        await fetchPage(config: config, refreshColumns: true, generation: generation)
    }

    public func fetchPage(
        config: ConnectionConfig,
        refreshColumns: Bool = false,
        generation: UInt64? = nil
    ) async {
        guard !currentTable.isEmpty else { return }
        let requestGen: UInt64
        if let generation {
            requestGen = generation
        } else {
            activeLoadTask?.cancel()
            activeLoadTask = nil
            loadGeneration &+= 1
            requestGen = loadGeneration
        }

        let targetSchema = currentSchema
        let targetTable = currentTable
        let targetOffset = offset
        let targetSortCol = sortColumn
        let targetSortDesc = sortDescending
        let needsColumns = refreshColumns || columns.isEmpty
        let knownHasPK: Bool? = needsColumns ? nil : hasPrimaryKey

        self.isLoading = true
        self.errorMessage = nil

        do {
            let result = try await load_table_page(
                config: config,
                schema: targetSchema,
                table: targetTable,
                offset: targetOffset,
                limit: limit,
                sortCol: targetSortCol,
                sortDesc: targetSortDesc,
                knownHasPrimaryKey: knownHasPK
            )

            guard !Task.isCancelled,
                  requestGen == self.loadGeneration,
                  self.currentSchema == targetSchema,
                  self.currentTable == targetTable else {
                return
            }

            if needsColumns {
                self.columns = result.columns
            }
            self.rows = result.page.rows
            self.hasMore = result.page.hasMore
            self.executionDurationMs = result.page.executionDurationMs
            self.dataVersion &+= 1
            self.isLoading = false
        } catch is CancellationError {
            return
        } catch {
            guard !Task.isCancelled,
                  requestGen == self.loadGeneration,
                  self.currentSchema == targetSchema,
                  self.currentTable == targetTable else {
                return
            }
            self.errorMessage = error.userFacingMessage
            self.isLoading = false
        }
    }

    public func notifyRowsUpdated() {
        dataVersion &+= 1
    }

    @MainActor
    public func prepareCsvExport(
        config: ConnectionConfig,
        initialScope: TableExportScope = .currentPage
    ) -> CsvExportViewModel? {
        guard !currentTable.isEmpty, !columns.isEmpty else { return nil }
        let vm = CsvExportViewModel(
            target: .tableData(
                config: config,
                schema: currentSchema,
                table: currentTable,
                columns: columns,
                fetchedRows: rows,
                offset: offset,
                hasPrimaryKey: hasPrimaryKey,
                sortCol: sortColumn,
                sortDesc: sortDescending,
                pendingChangesCount: totalStagedOperationsCount,
                stagedSummary: stagedSummaryText
            ),
            initialTableScope: initialScope
        )
        self.exportViewModel = vm
        return vm
    }

    public func nextPage(config: ConnectionConfig) {
        guard hasMore else { return }
        safeNavigate { [weak self] in
            guard let self = self else { return }
            self.activeLoadTask?.cancel()
            self.loadGeneration &+= 1
            let generation = self.loadGeneration
            self.offset += UInt64(self.limit)
            self.isLoading = true
            self.errorMessage = nil
            self.activeLoadTask = Task { @MainActor [weak self] in
                await self?.fetchPage(config: config, refreshColumns: false, generation: generation)
            }
        }
    }

    public func previousPage(config: ConnectionConfig) {
        guard offset >= UInt64(limit) else { return }
        safeNavigate { [weak self] in
            guard let self = self else { return }
            self.activeLoadTask?.cancel()
            self.loadGeneration &+= 1
            let generation = self.loadGeneration
            self.offset -= UInt64(self.limit)
            self.isLoading = true
            self.errorMessage = nil
            self.activeLoadTask = Task { @MainActor [weak self] in
                await self?.fetchPage(config: config, refreshColumns: false, generation: generation)
            }
        }
    }

    public func reloadTable(config: ConnectionConfig) {
        safeNavigate { [weak self] in
            guard let self = self else { return }
            self.activeLoadTask?.cancel()
            self.loadGeneration &+= 1
            let generation = self.loadGeneration
            self.isLoading = true
            self.errorMessage = nil
            self.activeLoadTask = Task { @MainActor [weak self] in
                await self?.fetchPage(config: config, refreshColumns: true, generation: generation)
            }
        }
    }

    public func discardAndReload(config: ConnectionConfig) async {
        clearStagedChanges()
        errorMessage = nil
        statusMessage = nil
        showingReviewSheet = false
        await fetchPage(config: config, refreshColumns: true)
    }

    public func recordUncertainCommitOutcome(message: String) {
        let pendingOps = stagedSummaryText
        self.hasUncertainCommitOutcome = true
        self.uncertainCommitOperationsSummary = pendingOps
        self.uncertainCommitDetails = message
        self.errorMessage = "Commit outcome uncertain (\(message)). Do not blindly re-apply — click Reload & Reconcile to check whether your \(pendingOps.isEmpty ? "changes" : pendingOps) actually committed."
    }

    public func reconcileUncertainCommit(config: ConnectionConfig) async {
        let pendingOps = uncertainCommitOperationsSummary ?? stagedSummaryText
        clearStagedChanges()
        errorMessage = nil
        showingReviewSheet = false
        await fetchPage(config: config)
        if errorMessage == nil {
            let scopeText = pendingOps.isEmpty ? "staged batch" : pendingOps
            statusMessage = "Reloaded live rows from PostgreSQL to reconcile uncertain commit (\(scopeText)). Verify whether those changes persisted before editing again."
        }
    }

    public func safeNavigate(action: @escaping () -> Void) {
        if !hasPendingChanges {
            action()
        } else {
            self.pendingNavigationAction = action
            self.showingUnsavedChangesAlert = true
        }
    }

    public func confirmDiscardAndNavigate() {
        clearStagedChanges()
        showingUnsavedChangesAlert = false
        let action = pendingNavigationAction
        pendingNavigationAction = nil
        action?()
    }

    public func cancelNavigation() {
        showingUnsavedChangesAlert = false
        pendingNavigationAction = nil
    }

    @discardableResult
    public func addDraftRow() -> Int? {
        guard isEditable, !isApplying, !columns.isEmpty else { return nil }
        errorMessage = nil
        let draft = StagedInsertRow()
        stagedInserts.append(draft)
        let newGridRow = rows.count + stagedInserts.count - 1
        selectedRowIndex = newGridRow
        if let firstEditableCol = columns.indices.first(where: { !isColumnAlwaysGenerated(columns[$0]) }) {
            pendingActiveCell = GridCoordinate(row: newGridRow, column: firstEditableCol + 1)
        }
        dataVersion &+= 1
        return newGridRow
    }

    public func stageTextEdit(row: Int, column: Int, text: String) {
        guard isCellEditable(row: row, column: column) else { return }
        let col = columns[column]
        if isDraftRow(row) {
            if text.isEmpty && !isColumnTextLike(col) {
                revertDraftCellToDefault(row: row, column: column)
                return
            }
            let parsed = parseCellValue(text: text, column: col)
            stageParsedValue(row: row, column: column, value: parsed)
        } else {
            let parsed = parseCellValue(text: text, column: col)
            stageParsedValue(row: row, column: column, value: parsed)
        }
    }

    public func stageNullEdit(row: Int, column: Int) {
        guard canSetNull(row: row, column: column) else { return }
        stageParsedValue(row: row, column: column, value: .null)
    }

    public func stageEmptyStringEdit(row: Int, column: Int) {
        guard isCellEditable(row: row, column: column), isColumnTextLike(columns[column]) else { return }
        stageParsedValue(row: row, column: column, value: .text(""))
    }

    public func revertDraftCellToDefault(row: Int, column: Int) {
        guard isDraftRow(row), isCellEditable(row: row, column: column) else { return }
        let draftIdx = row - rows.count
        stagedInserts[draftIdx].cells.removeValue(forKey: column)
    }

    public func setCellValue(row: Int, column: Int, value: CellValue) {
        guard isEditable, !value.isUnsupported else { return }
        if isDraftRow(row) {
            guard isCellEditable(row: row, column: column) else { return }
            if value.isNull, !canSetNull(row: row, column: column) { return }
            stageParsedValue(row: row, column: column, value: value)
            return
        }
        if !rows.isEmpty {
            guard isCellEditable(row: row, column: column) else { return }
            if value.isNull, !canSetNull(row: row, column: column) { return }
        }
        stageParsedValue(row: row, column: column, value: value)
    }

    private func stageParsedValue(row: Int, column: Int, value: CellValue) {
        if isDraftRow(row) {
            let draftIdx = row - rows.count
            stagedInserts[draftIdx].cells[column] = value
            return
        }
        let coord = GridCoordinate(row: row, column: column)
        if let orig = originalCellValue(row: row, column: column), orig == value {
            stagedEdits.removeValue(forKey: coord)
        } else {
            stagedEdits[coord] = value
        }
    }

    public func stageDeleteRow(row: Int) {
        guard canDeleteRow(row), !isApplying else { return }
        errorMessage = nil
        if isDraftRow(row) {
            let draftIdx = row - rows.count
            stagedInserts.remove(at: draftIdx)
            if totalGridRowCount == 0 {
                selectedRowIndex = nil
            } else if let sel = selectedRowIndex, sel >= totalGridRowCount {
                selectedRowIndex = totalGridRowCount - 1
            }
            dataVersion &+= 1
            return
        }
        // Clear any pending cell edits on this row before staging deletion so same-row conflict never happens
        stagedEdits = stagedEdits.filter { $0.key.row != row }
        stagedDeletes.insert(row)
        dataVersion &+= 1
    }

    public func unstageDeleteRow(row: Int) {
        guard stagedDeletes.remove(row) != nil else { return }
        dataVersion &+= 1
    }

    public func toggleDeleteSelectedRow() {
        guard let row = selectedRowIndex else { return }
        if isRowStagedForDeletion(row) {
            unstageDeleteRow(row: row)
        } else {
            stageDeleteRow(row: row)
        }
    }

    public func discardChanges() {
        clearStagedChanges()
    }

    private func clearStagedChanges() {
        stagedEdits.removeAll()
        stagedInserts.removeAll()
        stagedDeletes.removeAll()
        pendingActiveCell = nil
        hasUncertainCommitOutcome = false
        uncertainCommitOperationsSummary = nil
        uncertainCommitDetails = nil
        dataVersion &+= 1
    }

    public func discardEdit(row: Int, column: Int) {
        if isDraftRow(row) {
            revertDraftCellToDefault(row: row, column: column)
            return
        }
        stagedEdits.removeValue(forKey: GridCoordinate(row: row, column: column))
    }

    public func buildBatchMutationRequest() -> BatchMutationRequest? {
        guard isEditable, hasPendingChanges else { return nil }

        let pkCols = columns.filter { $0.isPrimaryKey }
        guard !pkCols.isEmpty else { return nil }

        // 1. Deletes (Phase 1)
        var deletes: [RowDelete] = []
        for rowIdx in stagedDeletes.sorted() {
            guard rowIdx >= 0, rowIdx < rows.count,
                  let xminStr = rowXmin(row: rowIdx) else {
                return nil
            }
            var pkNames: [String] = []
            var pkValues: [CellValue] = []
            for pkCol in pkCols {
                guard let pkIdx = columns.firstIndex(where: { $0.name == pkCol.name }),
                      let cellVal = originalCellValue(row: rowIdx, column: pkIdx),
                      !cellVal.isNull,
                      !cellVal.isUnsupported else {
                    return nil
                }
                pkNames.append(pkCol.name)
                pkValues.append(cellVal)
            }
            deletes.append(RowDelete(
                primaryKeyColumns: pkNames,
                primaryKeyValues: pkValues,
                originalXmin: xminStr
            ))
        }

        // 2. Updates (Phase 2)
        var rowEdits: [Int: [(colIdx: Int, value: CellValue)]] = [:]
        for (coord, val) in stagedEdits {
            guard !stagedDeletes.contains(coord.row), !val.isUnsupported else { continue }
            rowEdits[coord.row, default: []].append((coord.column, val))
        }

        var mutations: [RowMutation] = []
        for (rowIdx, edits) in rowEdits.sorted(by: { $0.key < $1.key }) {
            guard rowIdx < rows.count else { continue }
            guard let xminStr = rowXmin(row: rowIdx) else {
                return nil
            }

            var pkNames: [String] = []
            var pkValues: [CellValue] = []
            for pkCol in pkCols {
                guard let pkIdx = columns.firstIndex(where: { $0.name == pkCol.name }),
                      let cellVal = originalCellValue(row: rowIdx, column: pkIdx),
                      !cellVal.isNull,
                      !cellVal.isUnsupported else {
                    return nil
                }
                pkNames.append(pkCol.name)
                pkValues.append(cellVal)
            }

            var updatedCols: [String] = []
            var updatedVals: [CellValue] = []
            for edit in edits.sorted(by: { $0.colIdx < $1.colIdx }) {
                guard edit.colIdx < columns.count else { continue }
                let col = columns[edit.colIdx]
                if isColumnAlwaysGenerated(col) { continue }
                updatedCols.append(col.name)
                updatedVals.append(edit.value)
            }

            if !updatedCols.isEmpty {
                mutations.append(RowMutation(
                    primaryKeyColumns: pkNames,
                    primaryKeyValues: pkValues,
                    originalXmin: xminStr,
                    updatedColumns: updatedCols,
                    updatedValues: updatedVals
                ))
            }
        }

        // 3. Inserts (Phase 3)
        var inserts: [RowInsert] = []
        for draft in stagedInserts {
            var insertCols: [String] = []
            var insertVals: [CellValue] = []
            for colIdx in draft.cells.keys.sorted() {
                guard colIdx >= 0, colIdx < columns.count else { continue }
                let col = columns[colIdx]
                if isColumnAlwaysGenerated(col) { continue }
                guard let val = draft.cells[colIdx], !val.isUnsupported else {
                    return nil
                }
                insertCols.append(col.name)
                insertVals.append(val)
            }
            inserts.append(RowInsert(
                clientRowId: draft.id,
                columns: insertCols,
                values: insertVals
            ))
        }

        guard !deletes.isEmpty || !mutations.isEmpty || !inserts.isEmpty else {
            return nil
        }

        return BatchMutationRequest(
            schemaName: currentSchema,
            tableName: currentTable,
            mutations: mutations,
            inserts: inserts,
            deletes: deletes
        )
    }

    public func applyMutationResultLocally(_ result: BatchMutationResult, request: BatchMutationRequest) {
        // Apply DB-returned updated rows to matching row indices
        let editedRowsSorted = Array(Set(stagedEdits.keys.map(\.row)).subtracting(stagedDeletes)).sorted()
        for (idx, rowIdx) in editedRowsSorted.enumerated() where idx < result.updatedRows.count && rowIdx < rows.count {
            rows[rowIdx] = result.updatedRows[idx]
        }

        // Remove deleted persisted rows descending
        for rowIdx in stagedDeletes.sorted(by: >) where rowIdx < rows.count {
            rows.remove(at: rowIdx)
        }

        // Append DB-returned inserted rows (with generated keys, defaults, computed columns, and xmin)
        for inserted in result.insertedRows {
            rows.append(inserted.row)
        }

        clearStagedChanges()
    }

    public func applyStagedEdits(config: ConnectionConfig) async {
        guard hasPendingChanges else { return }

        if hasUncertainCommitOutcome {
            self.errorMessage = "Previous commit outcome is uncertain — blind re-apply is blocked to prevent duplicate writes. Click Reload & Reconcile to verify live database state first."
            return
        }

        if isReadOnly {
            self.errorMessage = "Read-only guardrail is active. Mutations are disabled."
            return
        }
        if isSystemSchema {
            self.errorMessage = "System schema '\(currentSchema)' is read-only. Catalog tables cannot be edited."
            return
        }
        let validationIssues = draftValidationIssues
        if !validationIssues.isEmpty {
            self.errorMessage = validationIssues.joined(separator: " ")
            return
        }

        guard let request = buildBatchMutationRequest() else {
            self.errorMessage = "Cannot apply changes: staged rows lack valid primary key or version identity, or contain unsupported values."
            return
        }

        self.isApplying = true
        self.errorMessage = nil

        do {
            let res = try await apply_table_mutations(config: config, request: request, readOnly: isReadOnly)
            applyMutationResultLocally(res, request: request)

            var parts: [String] = []
            if res.insertedCount > 0 {
                parts.append("\(res.insertedCount) inserted")
            }
            if res.updatedCount > 0 {
                parts.append("\(res.updatedCount) updated")
            }
            if res.deletedCount > 0 {
                parts.append("\(res.deletedCount) deleted")
            }
            let summary = parts.isEmpty ? "\(res.rowsAffected) applied" : parts.joined(separator: ", ")

            var generatedKeyNote = ""
            if let firstInserted = res.insertedRows.first {
                let pkIndices = columns.indices.filter { columns[$0].isPrimaryKey }
                let pkDescriptions: [String] = pkIndices.compactMap { pkIdx in
                    let rawIdx = pkIdx + 1
                    guard rawIdx < firstInserted.row.cells.count else { return nil }
                    return "\(columns[pkIdx].name)=\(firstInserted.row.cells[rawIdx].displayString)"
                }
                if !pkDescriptions.isEmpty && res.insertedCount == 1 {
                    generatedKeyNote = " (\(pkDescriptions.joined(separator: ", ")))"
                }
            }

            self.statusMessage = "Successfully applied: \(summary)\(generatedKeyNote)."
            self.isApplying = false
            self.showingReviewSheet = false

            if rows.isEmpty && offset >= UInt64(limit) {
                offset -= UInt64(limit)
            }
            await fetchPage(config: config)
        } catch let error as LucidError {
            self.isApplying = false
            if case .UncertainCommitOutcome = error {
                recordUncertainCommitOutcome(message: error.userFacingMessage)
            } else {
                self.errorMessage = error.userFacingMessage
            }
        } catch {
            self.isApplying = false
            self.errorMessage = "Failed to apply changes: \(error.userFacingMessage)"
        }
    }

    public func parseCellValue(text: String, column: ColumnMetadata) -> CellValue {
        let lowerType = column.pgTypeName.lowercased()

        // 1. Boolean
        if lowerType == "bool" || lowerType == "boolean" {
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
            if trimmed == "true" || trimmed == "t" || trimmed == "1" || trimmed == "yes" {
                return .boolean(true)
            } else if trimmed == "false" || trimmed == "f" || trimmed == "0" || trimmed == "no" {
                return .boolean(false)
            }
        }

        // 2. Integers (exact integer / oid types only; avoid matching "point" or "interval")
        let intTypes: Set<String> = [
            "int2", "int4", "int8",
            "smallint", "integer", "bigint",
            "serial", "serial2", "serial4", "serial8",
            "smallserial", "bigserial", "oid"
        ]
        if intTypes.contains(lowerType) {
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            if let val = Int64(trimmed) {
                return .integer(val)
            }
        }

        // 3. Exact Numeric / Decimal
        if lowerType == "numeric" || lowerType == "decimal" {
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            return .decimal(trimmed)
        }

        // 4. Floating point (float4, float8, real, double precision)
        if lowerType == "float4" || lowerType == "float8" || lowerType == "real" || lowerType == "double precision" {
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            if let val = Double(trimmed) {
                return .float(val)
            }
        }

        // 5. JSON / JSONB
        if lowerType == "json" || lowerType == "jsonb" {
            return .json(text)
        }

        // 6. UUID
        if lowerType == "uuid" {
            return .uuid(text.trimmingCharacters(in: .whitespacesAndNewlines))
        }

        // 7. Date
        if lowerType == "date" {
            return .date(text.trimmingCharacters(in: .whitespacesAndNewlines))
        }

        // 8. Time
        if lowerType == "time" || lowerType == "timetz" || lowerType == "time without time zone" || lowerType == "time with time zone" {
            return .time(text.trimmingCharacters(in: .whitespacesAndNewlines))
        }

        // 9. Timestamps
        if lowerType == "timestamptz" || lowerType.contains("with time zone") {
            return .timestampWithTimeZone(text.trimmingCharacters(in: .whitespacesAndNewlines))
        }
        if lowerType == "timestamp" || lowerType.contains("without time zone") {
            return .timestampWithoutTimeZone(text.trimmingCharacters(in: .whitespacesAndNewlines))
        }

        // 10. Default / Text / Varchar
        return .text(text)
    }
